// Extracts the facts the highlighter needs from crml.g4 that the generated
// lexer does not carry: which keywords name built-in types, and which are
// boolean values. Written next to the generated lexer so both always come from
// the same grammar.
import { readFileSync, writeFileSync } from "node:fs";
import { fileURLToPath } from "node:url";

const grammarPath = fileURLToPath(new URL(
    "../../../submodules/language/src/main/antlr/crml/language/grammar/crml.g4", import.meta.url));
const outPath = fileURLToPath(new URL("../src/generated/grammarInfo.ts", import.meta.url));

const grammar = readFileSync(grammarPath, "utf8");

/** Returns the quoted literals of a parser rule made only of alternatives such as 'Real' | 'Boolean'. */
function literalsOf(ruleName) {
    const rule = new RegExp(`^${ruleName}\\s*:([^;]*);`, "m").exec(grammar);
    if (!rule) {
        throw new Error(`No ${ruleName} rule in ${grammarPath}`);
    }
    return [...rule[1].matchAll(/'([^']+)'/g)].map(m => m[1]);
}

writeFileSync(outPath,
    "// Generated by scripts/grammar-info.mjs from crml.g4. Do not edit.\n" +
    `export const BUILTIN_TYPES: readonly string[] = ${JSON.stringify(literalsOf("builtin_type"))};\n` +
    `export const BOOLEAN_VALUES: readonly string[] = ${JSON.stringify(literalsOf("boolean_value"))};\n`);
